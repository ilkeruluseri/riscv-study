"""Extract unchanged functions from the local llama.cpp checkout."""

from pathlib import Path
import sys


def extract(source, name):
    pos = source.index("void " + name + "(")
    start = source.rfind("\n", 0, pos) + 1
    brace = source.index("{", pos)
    depth = 1
    end = brace + 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


root = Path(sys.argv[1])
rv = (root / "ggml/src/ggml-cpu/arch/riscv/quants.c").read_text()
generic = (root / "ggml/src/ggml-cpu/quants.c").read_text()
parts = ["""// Generated by extract.py; function bodies are copied unchanged.
#include <assert.h>
#include <stdio.h>
#include <string.h>
#include <riscv_vector.h>
#define GGML_COMMON_IMPL_C
#include "ggml-common.h"
#include "ggml-quants.h"
#include "ggml-impl.h"
#define NOINLINE __attribute__((noinline))
#define UNUSED GGML_UNUSED
#define GGML_CPU_FP16_TO_FP32(x) GGML_FP16_TO_FP32(x)
"""]
for kind in ("iq4_nl", "mxfp4"):
    name = f"ggml_vec_dot_{kind}_q8_0"
    parts.append(extract(generic, name + "_generic"))
    parts.extend(extract(rv, name + suffix) for suffix in ("_vl128", "_vl256", ""))
Path(__file__).with_name("kernels.inc").write_text("\n\n".join(parts) + "\n")
